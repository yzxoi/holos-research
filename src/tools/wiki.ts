function slugify(title: string, firstAuthor?: string, year?: number): string {
  const keyword = title
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, "")
    .split(/\s+/)
    .filter(
      (w) =>
        w.length > 3 &&
        !["that", "this", "with", "from", "using", "based", "which", "their", "where", "when"].includes(w),
    )
    .slice(0, 3)
    .join("_");

  const author = firstAuthor ? (firstAuthor.split(",").at(0)?.trim().toLowerCase().replace(/\s+/g, "") ?? "") : "";
  const y = year?.toString() ?? "";

  const parts = [author, y, keyword].filter(Boolean);
  return parts.join("_") || "untitled";
}

function bibEntry(
  slug: string,
  title: string,
  authors: string[],
  year: number | undefined,
  venue: string | undefined,
  arxiv: string | undefined,
): string {
  const key = slug.replace(/_/g, "");
  const authorStr = authors.length > 0 ? authors.join(" and ") : "Unknown";
  const lines = venue
    ? [
        `@article{${key},`,
        `  title={${title}},`,
        `  author={${authorStr}},`,
        year ? `  year={${year}},` : "",
        `  journal={${venue}},`,
        arxiv ? `  note={arXiv:${arxiv}},` : "",
        `}`,
      ]
    : [
        `@misc{${key},`,
        `  title={${title}},`,
        `  author={${authorStr}},`,
        year ? `  year={${year}},` : "",
        arxiv ? `  url={https://arxiv.org/abs/${arxiv}},` : "",
        `}`,
      ];
  return lines.filter(Boolean).join("\n") + "\n";
}

