const PAPER_MD_TEMPLATE = (title: string, content?: PaperContent) => {
  const c = content ?? {};
  return [
    `# ${title}`,
    "",
    "## One-line Thesis",
    "",
    c.thesis || "(single sentence capturing the paper's core contribution)",
    "",
    "## Problem / Gap",
    "",
    c.problem || "",
    "",
    "## Method",
    "",
    c.method || "",
    "",
    "## Key Results",
    "",
    c.key_results || "",
    "",
    "## Assumptions",
    "",
    c.assumptions || "",
    "",
    "## Limitations / Failure Modes",
    "",
    c.limitations || "",
    "",
    "## Reusable Ingredients",
    "",
    c.reusable || "(techniques, datasets, or insights that could be repurposed)",
    "",
    "## Open Questions",
    "",
    c.open_questions || "",
    "",
    "## Connections",
    "",
    "(auto-generated from edges.jsonl — do not edit manually)",
    "",
    "## Relevance to This Project",
    "",
    c.project_relevance || "",
    "",
  ].join("\n");
};

