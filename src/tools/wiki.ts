export const researchWiki = tool({
  description: DESCRIPTION,
  args: {
    action: z
      .enum(["ingest_paper", "link", "register_gap", "update_entry", "query", "lint", "verify_bib", "stats"])
      .describe("Operation to perform"),

    title: z.string().optional().describe("Paper title. Required for ingest_paper."),
    authors: z.array(z.string()).optional().describe("Author list. For ingest_paper."),
    year: z.number().optional().describe("Publication year. For ingest_paper."),
    venue: z.string().optional().describe("Venue (e.g. 'ICML 2026', 'arXiv'). For ingest_paper."),
    arxiv: z.string().optional().describe("arXiv ID (e.g. '2501.12345'). For ingest_paper."),
    doi: z.string().optional().describe("DOI. For ingest_paper."),
    tags: z.array(z.string()).optional().describe("Topic tags. For ingest_paper or update_entry."),
    relevance: PaperRelevance.optional().describe(
      "Relevance: core, related, peripheral. For ingest_paper or update_entry.",
    ),
    slug_override: z.string().optional().describe("Override auto-generated slug. For ingest_paper."),

    thesis: z.string().optional().describe("One-line thesis of the paper. For ingest_paper — fills the md template."),
    method: z.string().optional().describe("Method summary. For ingest_paper — fills the md template."),
    key_results: z.string().optional().describe("Key results with numbers. For ingest_paper — fills the md template."),
    limitations: z
      .string()
      .optional()
      .describe("Limitations and failure modes. For ingest_paper — fills the md template."),
    project_relevance: z
      .string()
      .optional()
      .describe("Why this paper matters for our project. For ingest_paper — fills the md template."),

    from: z.string().optional().describe("Source entity. For link."),
    to: z.string().optional().describe("Target entity. For link."),
    edge_type: EdgeType.optional().describe("Relationship type. For link."),
    evidence: z.string().optional().describe("Why this relationship exists. For link."),

    description: z.string().optional().describe("Gap description. Required for register_gap."),
    source_paper: z.string().optional().describe("Paper slug that reveals this gap. For register_gap."),

    target_id: z.string().optional().describe("Paper slug or gap ID to update. For update_entry."),
    field: z.string().optional().describe("Field to update. For update_entry."),
    value: z.string().optional().describe("New value. For update_entry."),

    // query
    force: z.boolean().optional().describe("Force regenerate LIT_CONTEXT.md even if not stale. For query."),
  },
  async execute(params, ctx) {
    return withGuard(async () => {
      if (!(await ResearchFS.isInitialized())) return notInitialized();
      const state = await ResearchFS.readYaml<StateYaml>(ResearchFS.resolve("state.yaml"));
      const activePhaseRun = state?.focus?.active_phase_run;
      const signal = ctx?.abort;
      switch (params.action) {
        case "ingest_paper":
          return handleIngestPaper(params, activePhaseRun, signal);
        case "link":
          return handleLink(params, activePhaseRun);
        case "register_gap":
          return handleRegisterGap(params, activePhaseRun);
        case "update_entry":
          return handleUpdateEntry(params, activePhaseRun);
        case "query":
          return handleQuery(params);
        case "lint":
          return handleLint(params);
        case "verify_bib":
          return handleVerifyBib(params);
        case "stats":
          return handleStats(params);
        default:
          return {
            title: "Unknown action",
            output: `Unknown action: ${params.action}`,
            metadata: mdMeta({ error: "unknown_action" }),
          };
      }
    });
  },
});
