async function entityExists(id: string): Promise<boolean> {
  // Gap IDs: validate they actually exist in gap_map.yaml
  if (/^G\d+$/.test(id)) {
    try {
      const gapMap = await ResearchFS.readYaml<{ gaps: Array<{ id: string }> }>(
        ResearchFS.resolve("literature/gap_map.yaml"),
      );
      return gapMap?.gaps?.some((g) => g.id === id) ?? false;
    } catch {
      return false;
    }
  }

  // Literature papers: check literature/papers/{slug}.yaml
  const litPaperPath = ResearchFS.resolve("literature/papers", `${id}.yaml`);
  if (await ResearchFS.exists(litPaperPath)) return true;

  const auxiliaryDirs: Array<{ prefix: string; dir: string }> = [
    { prefix: "rqg_", dir: "rqg" },
    { prefix: "diag_", dir: "diagnoses" },
    { prefix: "code_artifact_", dir: "code_artifacts" },
    { prefix: "artifact_", dir: "code_artifacts" },
  ];
  for (const { prefix, dir } of auxiliaryDirs) {
    if (id.startsWith(prefix)) {
      return ResearchFS.exists(ResearchFS.resolve(dir, `${id}.yaml`));
    }
  }

  // Research entities with known prefixes (idea_001 → ideas/idea_001.yaml)
  const underscoreIdx = id.indexOf("_");
  if (underscoreIdx > 0) {
    const prefix = id.slice(0, underscoreIdx);
    const dir = ENTITY_DIRS[prefix];
    if (dir) {
      const filePath = ResearchFS.resolve(dir, `${id}.yaml`);
      return ResearchFS.exists(filePath);
    }
  }

  // Unknown prefix — block edge creation to prevent dangling references
  log.warn("Wiki", `entityExists: unknown prefix in "${id}" — blocking edge creation`);
  return false;
}

